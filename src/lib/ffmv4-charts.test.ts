describe('Pinson charts match The Flying-fox Manual v4 (s3.025)', () => {
  it('growth columns, days 1-84', () => {
    expect(PINSON_GHFF_CHART.filter((r) => r[0] <= 84)).toEqual(FFMV4_GROWTH);
  });

  it('Biolac v4 feed volumes and schedules, days 1-78', () => {
    expect(PINSON_FEED_CHART).toEqual(FFMV4_BIOLAC);
  });

  it("cow's milk v3 feed volumes and schedules, days 1-78", () => {
    expect(PINSON_COWS_FEED_CHART).toEqual(FFMV4_COWS);
  });

  it('every printed schedule sums to its daily total', () => {
    for (const [, ml, s] of [...FFMV4_BIOLAC, ...FFMV4_COWS]) {
      expect(s.reduce((a, b) => a + b, 0)).toBe(ml);
    }
  });
});
